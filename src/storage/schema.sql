-- File tracking for incremental parsing
CREATE TABLE IF NOT EXISTS file_meta (
  file_path TEXT PRIMARY KEY,
  hash TEXT NOT NULL,
  last_indexed INTEGER NOT NULL
);

-- Core AST nodes
CREATE TABLE IF NOT EXISTS nodes (
  id TEXT PRIMARY KEY,            -- e.g. "src/auth/service.ts::validateToken"
  file_path TEXT NOT NULL,
  name TEXT NOT NULL,
  kind TEXT NOT NULL,             -- "function", "class", "interface", "endpoint", "type", "variable"
  signature TEXT,
  summary TEXT,                   -- Generated by LLM during explore
  start_line INTEGER NOT NULL DEFAULT 0,
  end_line INTEGER NOT NULL DEFAULT 0,
  FOREIGN KEY (file_path) REFERENCES file_meta(file_path) ON DELETE CASCADE
);

-- Directed dependency edges
CREATE TABLE IF NOT EXISTS edges (
  source_id TEXT NOT NULL,
  target_id TEXT NOT NULL,
  relation TEXT NOT NULL,         -- "CALLS", "IMPORTS", "EXTENDS", "DEPENDS_ON"
  PRIMARY KEY (source_id, target_id, relation),
  FOREIGN KEY (source_id) REFERENCES nodes(id) ON DELETE CASCADE
);

-- Full-Text Search (FTS5) for instant lexical retrieval
CREATE VIRTUAL TABLE IF NOT EXISTS nodes_fts USING fts5(
  id UNINDEXED,
  name,
  kind,
  signature,
  summary,
  content='nodes',
  content_rowid='rowid'
);

-- Trigger: keep FTS5 in sync with nodes table on insert
CREATE TRIGGER IF NOT EXISTS nodes_ai AFTER INSERT ON nodes BEGIN
  INSERT INTO nodes_fts(rowid, id, name, kind, signature, summary) 
  VALUES (new.rowid, new.id, new.name, new.kind, coalesce(new.signature, ''), coalesce(new.summary, ''));
END;

-- Trigger: keep FTS5 in sync with nodes table on delete
CREATE TRIGGER IF NOT EXISTS nodes_ad AFTER DELETE ON nodes BEGIN
  INSERT INTO nodes_fts(nodes_fts, rowid, id, name, kind, signature, summary) 
  VALUES ('delete', old.rowid, old.id, old.name, old.kind, coalesce(old.signature, ''), coalesce(old.summary, ''));
END;

-- Trigger: keep FTS5 in sync with nodes table on update
CREATE TRIGGER IF NOT EXISTS nodes_au AFTER UPDATE ON nodes BEGIN
  INSERT INTO nodes_fts(nodes_fts, rowid, id, name, kind, signature, summary) 
  VALUES ('delete', old.rowid, old.id, old.name, old.kind, coalesce(old.signature, ''), coalesce(old.summary, ''));
  INSERT INTO nodes_fts(rowid, id, name, kind, signature, summary) 
  VALUES (new.rowid, new.id, new.name, new.kind, coalesce(new.signature, ''), coalesce(new.summary, ''));
END;
